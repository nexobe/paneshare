import Foundation

/// One side's clipboard settings, sent whenever they change. `active` is true while a viewer has
/// one of this host's windows in front; only the viewer's value counts.
public struct ClipboardState: Codable, Equatable, Sendable {
    public var enabled: Bool
    public var active: Bool
    public init(enabled: Bool, active: Bool) { self.enabled = enabled; self.active = active }
}

/// The rules of clipboard sync, for one session. Text moves only when both Macs turned sync on and
/// a remote window is in front on the viewer. The app reads the clipboard only after `canSync`.
public struct ClipboardSync: Equatable, Sendable {
    public static let maxBytes = 1_048_576
    /// Markers from nspasteboard.org: the copying app says this must not leave the clipboard history.
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    public var localEnabled = false
    public var peerEnabled = false
    public var focused = false
    /// The clipboard change already handled: sent, skipped, or written by this class's caller.
    private var handledChange: Int?

    public init() {}

    public var canSync: Bool { localEnabled && peerEnabled && focused }

    /// True when the clipboard has changed since the last call that handled it.
    public func needsRead(changeCount: Int) -> Bool { canSync && changeCount != handledChange }

    /// What to send for a clipboard change, or nil when it must stay on this Mac.
    public mutating func localChanged(changeCount: Int, types: [String], text: String?) -> Data? {
        guard needsRead(changeCount: changeCount) else { return nil }
        handledChange = changeCount
        guard Self.privateTypes.isDisjoint(with: types), let text, !text.isEmpty else { return nil }
        let data = Data(text.utf8)
        return data.count <= Self.maxBytes ? data : nil
    }

    /// The text to put on this Mac's clipboard, or nil when the message must be dropped.
    public func received(_ payload: Data) -> String? {
        guard canSync, !payload.isEmpty, payload.count <= Self.maxBytes else { return nil }
        return String(data: payload, encoding: .utf8)
    }

    /// Call after writing received text, so that it isn't sent straight back.
    public mutating func wrote(changeCount: Int) { handledChange = changeCount }
}
